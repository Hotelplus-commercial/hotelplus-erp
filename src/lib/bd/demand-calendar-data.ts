export const seasonsOf = (p: ProvinceDemand) => p.months.split("") as Season[];
export function filterProvinces(list: ProvinceDemand[], q: string, region: Region | "All"): ProvinceDemand[] {
  const s = q.trim().toLowerCase();
  return list.filter((p) => (region === "All" || p.region === region) && (!s || p.en.toLowerCase().includes(s) || p.th.includes(s)));
}
export function summaryOf(p: ProvinceDemand) {
  const m = seasonsOf(p);
  return { H: m.filter((x) => x === "H").length, M: m.filter((x) => x === "M").length, L: m.filter((x) => x === "L").length };
}
